export const generateForumPosts = async (): Promise<Post[]> => {
  const apiKey = process.env.API_KEY;
  if (!apiKey) {
    console.warn("No API key found, using fallback data.");
    return FALLBACK_POSTS;
  }

  try {
    const ai = new GoogleGenAI({ apiKey });
    const response = await ai.models.generateContent({
      model: "gemini-2.5-flash",
      contents: "Generate 15 realistic Chinese motorcycle forum posts (NGA style style). The topic should be about motorcycles, riding, gear, or maintenance. JSON format.",
      config: {
        responseMimeType: "application/json",
        responseSchema: {
          type: Type.ARRAY,
          items: {
            type: Type.OBJECT,
            properties: {
              id: { type: Type.STRING },
              title: { type: Type.STRING },
              author: { type: Type.STRING },
              content: { type: Type.STRING },
              likes: { type: Type.INTEGER },
              commentsCount: { type: Type.INTEGER },
              time: { type: Type.STRING },
              comments: {
                type: Type.ARRAY,
                items: {
                    type: Type.OBJECT,
                    properties: {
                        id: { type: Type.STRING },
                        author: { type: Type.STRING },
                        content: { type: Type.STRING },
                        time: { type: Type.STRING }
                    }
                }
              }
            }
          }
        }
      }
    });

    if (response.text) {
      const posts = JSON.parse(response.text) as Post[];
      // Ensure we have exactly 15 or slice/fill
      return posts.length >= 15 ? posts.slice(0, 15) : [...posts, ...FALLBACK_POSTS.slice(0, 15 - posts.length)];
    }
    return FALLBACK_POSTS;
  } catch (error) {
    console.error("Gemini API Error:", error);
    return FALLBACK_POSTS;
  }
};